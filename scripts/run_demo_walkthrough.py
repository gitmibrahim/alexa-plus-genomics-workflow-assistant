async def _rpc_call(
    client: httpx.AsyncClient,
    token: str,
    method: str,
    params: dict[str, Any] | None = None,
    rpc_id: int = 1,
) -> dict[str, Any]:
    resp = await client.post(
        "/mcp",
        headers={"Authorization": f"Bearer {token}"},
        json={"jsonrpc": "2.0", "id": rpc_id, "method": method, "params": params or {}},
    )
    assert resp.status_code == 200, f"Expected HTTP 200, got {resp.status_code}: {resp.text}"
    body: dict[str, Any] = resp.json()
    return body["result"]


async def _tool_call(
    client: httpx.AsyncClient,
    token: str,
    name: str,
    arguments: dict[str, Any],
    rpc_id: int = 1,
) -> tuple[bool, dict[str, Any]]:
    result = await _rpc_call(
        client,
        token,
        "tools/call",
        {"name": name, "arguments": arguments},
        rpc_id=rpc_id,
    )
    is_error = bool(result.get("isError", False))
    structured: dict[str, Any] = result.get("structuredContent", {})
    return is_error, structured


async def run_walkthrough(
    *,
    mode: str = "local",
    remote_endpoint: str | None = None,
    bearer_token: str | None = None,
) -> dict[str, Any]:
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp_dir:
        db_file = Path(tmp_dir) / "walkthrough_genomics.db"
        resource_uri = remote_endpoint or "https://mcp.checkpoint.local/mcp"
        issuer = EphemeralOAuth2TestIssuer(default_resource_uri=resource_uri)
        sink = InMemoryNotificationSink()
        policy = GenomicsDomainPolicy()

        def _build_local_app() -> MCPWorkflowServer:
            backend = LocalBackend(db_file, policy, notification_port=sink)
            verifier = OAuth2TokenVerifier(
                issuer_url=issuer.issuer_url,
                resource_uri=resource_uri,
                jwks_json=issuer.get_jwks_json(),
                profile=AuthProfile.ALEXA_CATEGORY_MCP,
            )
            return MCPWorkflowServer(backend=backend, token_verifier=verifier)

        _print_banner(mode, resource_uri)

        # Acquire Tier 1 (mcp:service) and Tier 2 (mcp:tools via PKCE S256) tokens
        service_token = bearer_token or issuer.issue_service_token(scope="mcp:service")
        verifier_str, challenge_str = issuer.generate_pkce_pair()
        auth_code = issuer.create_authorization_code(
            client_id="alexa-genomics-client",
            principal_id="tech-sarah-chen",
            redirect_uri="https://alexa.amazon.com/api/skill/link/checkpoint",
            code_challenge=challenge_str,
            code_challenge_method="S256",
            scope="mcp:tools",
        )
        user_token = bearer_token or issuer.exchange_authorization_code(
            code=auth_code,
            client_id="alexa-genomics-client",
            redirect_uri="https://alexa.amazon.com/api/skill/link/checkpoint",
            code_verifier=verifier_str,
        )

        server_part1 = _build_local_app()
        transport1 = httpx.ASGITransport(app=server_part1.create_asgi_app())

        async with httpx.AsyncClient(transport=transport1, base_url="https://mcp.checkpoint.local") as client:
            # Step 0: Verify Headerless 401 & Two-Tier Discovery
            unauth_resp = await client.post("/mcp", json={"jsonrpc": "2.0", "id": 0, "method": "ping"})
            assert unauth_resp.status_code == 401
            assert "www-authenticate" not in {k.lower() for k in unauth_resp.headers}
            print("[Step 0] Verified Headerless HTTP 401 & OAuth 2.1 PKCE (S256) Handshake")

            init_res = await _rpc_call(client, service_token, "initialize", rpc_id=1)
            tools_res = await _rpc_call(client, service_token, "tools/list", rpc_id=2)
            print(
                f"         MCP Protocol: {init_res['protocolVersion']} | "
                f"Tools Exposed: {len(tools_res['tools'])}"
            )

            # Step 1: Start WGS Clinical QC on FLOWCELL-WGS-07
            is_err, s1 = await _tool_call(
                client,
                user_token,
                "start_inspection",
                {
                    "inspection_type": "wgs_clinical_qc",
                    "asset_id": "FLOWCELL-WGS-07",
                    "idempotency_key": "walkthrough-start-07",
                    "notification_prefs": {
                        "on_pause": True,
                        "on_revision": True,
                        "on_blocked": True,
                        "on_status": True,
                        "on_completion": True,
                        "channels": ["voice_summary", "lims_webhook"],
                    },
                },
                rpc_id=3,
            )
            assert not is_err and s1["status"] == "RUNNING" and s1["duplicate"] is False
            exec_id = s1["execution_id"]
            print(f"[Step 1] Started WGS QC on FLOWCELL-WGS-07 -> execution_id={exec_id}")

            # Step 2: Record Valid Step 1 (Qubit DNA Yield) & Step 2 (TapeStation Fragment Size)
            is_err, r1 = await _tool_call(
                client,
                user_token,
                "record_inspection_result",
                {
                    "execution_id": exec_id,
                    "step_id": "dna_concentration_ng_ul",
                    "value": 42.5,
                    "unit": "ng/uL",
                    "idempotency_key": "walkthrough-step1-07",
                },
                rpc_id=4,
            )
            assert not is_err and r1["accepted"] is True
            is_err, r2 = await _tool_call(
                client,
                user_token,
                "record_inspection_result",
                {
                    "execution_id": exec_id,
                    "step_id": "fragment_size_bp",
                    "value": 475.0,
                    "unit": "bp",
                    "idempotency_key": "walkthrough-step2-07",
                },
                rpc_id=5,
            )
            assert not is_err and r2["accepted"] is True
            print(
                "[Step 2] Recorded Valid Readings: Qubit=42.5 ng/uL, TapeStation=475.0 bp -> "
                f"Next Pending: {r2['next_step']['step_id']}"
            )

            # Step 3: Pause Session for Wet-Lab Incubation & Emit Notification (AC18)
            is_err, pause_res = await _tool_call(
                client,
                user_token,
                "configure_notifications",
                {
                    "execution_id": exec_id,
                    "pause_session": True,
                    "idempotency_key": "walkthrough-pause-07",
                },
                rpc_id=6,
            )
            assert not is_err and pause_res["session_paused"] is True
            print(
                f"[Step 3] Paused Session for Incubation -> session_paused={pause_res['session_paused']} "
                f"| Notification Queued: {pause_res['notification_queued']}"
            )

            # Step 4: Demonstrate Asset Lock Collision & Multi-Session Disambiguation (AC17)
            is_err, lock_err = await _tool_call(
                client,
                user_token,
                "start_inspection",
                {
                    "inspection_type": "wgs_clinical_qc",
                    "asset_id": "FLOWCELL-WGS-07",
                    "idempotency_key": "walkthrough-collide-07",
                },
                rpc_id=7,
            )
            assert is_err and lock_err["details"]["reason"] == "ASSET_ALREADY_UNDER_INSPECTION"

            is_err, s_second = await _tool_call(
                client,
                user_token,
                "start_inspection",
                {
                    "inspection_type": "wgs_clinical_qc",
                    "asset_id": "FLOWCELL-WGS-08",
                    "idempotency_key": "walkthrough-start-08",
                },
                rpc_id=8,
            )
            assert not is_err and s_second["status"] == "RUNNING"

            is_err, ambig_err = await _tool_call(
                client,
                user_token,
                "get_inspection_status",
                {},
                rpc_id=9,
            )
            assert is_err and ambig_err["details"]["reason"] == "AMBIGUOUS_ACTIVE_SESSION"
            active_cnt = ambig_err["details"].get("active_count", len(ambig_err["details"].get("active_executions", [])))
            print(
                "[Step 4] Verified Collision Guards (AC17): Duplicate start on FLOWCELL-WGS-07 blocked "
                f"& Ambiguous Resume across {active_cnt} active flow cells caught"
            )

        # Simulate Server Process Restart Against Persistent SQLite WAL File (AC3, AC4)
        server_part2 = _build_local_app()
        transport2 = httpx.ASGITransport(app=server_part2.create_asgi_app())

        async with httpx.AsyncClient(transport=transport2, base_url="https://mcp.checkpoint.local") as client2:
            # Step 5: Authoritative Resume on FLOWCELL-WGS-07 After Server Restart
            is_err, status_res = await _tool_call(
                client2,
                user_token,
                "get_inspection_status",
                {"asset_id": "FLOWCELL-WGS-07", "emit_notification": True},
                rpc_id=10,
            )
            assert not is_err and status_res["execution_id"] == exec_id
            assert len(status_res["completed_steps"]) == 2
            assert status_res["pending_step"]["step_id"] == "loading_molarity_pm"
            print(
                f"[Step 5] Resumed FLOWCELL-WGS-07 After Server Restart -> "
                f"Completed Steps: {len(status_res['completed_steps'])}, "
                f"Pending: {status_res['pending_step']['step_id']}"
            )

            # Step 6: Idempotent Retry of Step 2 Reading (AC5)
            is_err, replay_res = await _tool_call(
                client2,
                user_token,
                "record_inspection_result",
                {
                    "execution_id": exec_id,
                    "step_id": "fragment_size_bp",
                    "value": 475.0,
                    "unit": "bp",
                    "idempotency_key": "walkthrough-step2-07",
                },
                rpc_id=11,
            )
            assert not is_err and replay_res["duplicate"] is True and replay_res["accepted"] is True
            print(f"[Step 6] Replayed Step 2 with Same Idempotency Key -> duplicate={replay_res['duplicate']}")

            # Step 7: Out-of-Range Loading Molarity (310.0 pM > 250.0 pM Max) Triggers BLOCKED (AC8)
            is_err, block_res = await _tool_call(
                client2,
                user_token,
                "record_inspection_result",
                {
                    "execution_id": exec_id,
                    "step_id": "loading_molarity_pm",
                    "value": 310.0,
                    "unit": "pM",
                    "idempotency_key": "walkthrough-step3-high-07",
                },
                rpc_id=12,
            )
            assert not is_err and block_res["accepted"] is False and block_res["status"] == "BLOCKED"
            exc_id = block_res["active_exception"]["exception_id"]
            print(
                f"[Step 7] Out-of-Range Molarity (310.0 pM) Recorded -> status={block_res['status']} "
                f"| exception_id={exc_id}"
            )

            # Step 8: Attempt Completion While BLOCKED -> Rejected (AC9)
            is_err, reject_comp = await _tool_call(
                client2,
                user_token,
                "complete_inspection",
                {"execution_id": exec_id, "idempotency_key": "walkthrough-complete-blocked"},
                rpc_id=13,
            )
            assert is_err and reject_comp["error_code"] == "WORKFLOW_BLOCKED"
            print(f"[Step 8] Rejected Complete While Blocked -> error_code={reject_comp['error_code']}")

            # Step 9: Reject Unapproved Override ("FORCE_PASS") & Apply Whitelisted Dilution Resolution (AC10)
            is_err, bad_res = await _tool_call(
                client2,
                user_token,
                "resolve_inspection_exception",
                {
                    "execution_id": exec_id,
                    "exception_id": exc_id,
                    "resolution": "FORCE_PASS",
                    "idempotency_key": "walkthrough-bad-resolve",
                },
                rpc_id=14,
            )
            assert is_err and bad_res["error_code"] == "INVALID_INPUT"

            is_err, good_res = await _tool_call(
                client2,
                user_token,
                "resolve_inspection_exception",
                {
                    "execution_id": exec_id,
                    "exception_id": exc_id,
                    "resolution": "DILUTE_LIBRARY_TO_TARGET_MOLARITY_AND_RETEST",
                    "idempotency_key": "walkthrough-good-resolve",
                },
                rpc_id=15,
            )
            assert not is_err and good_res["status"] == "RUNNING"
            assert good_res["pending_step"]["step_id"] == "loading_molarity_pm"
            print(
                "[Step 9] Rejected 'FORCE_PASS' & Applied Whitelisted Resolution: "
                f"{good_res['resolution_recorded']} -> status={good_res['status']}"
            )

            # Step 10: Record Valid Re-Quantified Molarity (215.0 pM)
            is_err, valid_s3 = await _tool_call(
                client2,
                user_token,
                "record_inspection_result",
                {
                    "execution_id": exec_id,
                    "step_id": "loading_molarity_pm",
                    "value": 215.0,
                    "unit": "pM",
                    "idempotency_key": "walkthrough-step3-valid-07",
                },
                rpc_id=16,
            )
            assert not is_err and valid_s3["accepted"] is True and valid_s3["next_step"] is None
            print("[Step 10] Recorded Re-Quantified Molarity (215.0 pM) -> All 3 WGS QC Gates Satisfied")

            # Step 11: Safe Completion & Release to ICA -> DRAGEN -> Emedgene Pipeline
            is_err, comp_res = await _tool_call(
                client2,
                user_token,
                "complete_inspection",
                {"execution_id": exec_id, "idempotency_key": "walkthrough-complete-final-07"},
                rpc_id=17,
            )
            assert not is_err and comp_res["status"] == "COMPLETED"
            summary = comp_res["summary"]
            print(
                f"[Step 11] Completed WGS QC Run -> status={comp_res['status']} | "
                f"audit_reference={summary['audit_reference']}"
            )
            print(
                "          Downstream Bioinformatics Handoff: "
                f"{json.dumps(summary['metadata'], sort_keys=True)}"
            )
            print(
                f"          Total Live Notifications Dispatched: {len(sink.delivered_records)}"
            )
            print("=" * 84)
            return {
                "execution_id": exec_id,
                "final_status": comp_res["status"],
                "summary": summary,
                "notifications_dispatched": len(sink.delivered_records),
            }


def main() -> None:
    parser = argparse.ArgumentParser(description="Run Checkpoint 11-step WGS QC walkthrough.")
    parser.add_argument("--mode", choices=["local", "remote"], default="local")
    parser.add_argument("--endpoint", default=None)
    args = parser.parse_args()
    asyncio.run(run_walkthrough(mode=args.mode, remote_endpoint=args.endpoint))


if __name__ == "__main__":
    main()
